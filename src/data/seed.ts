function payout(
  partial: Omit<Payout, 'netAed' | 'platformFeeAed' | 'grossAed' | 'amountAed'> & {
    grossAed: number;
    feeRate?: number;
  },
): Payout {
  const feeRate = partial.feeRate ?? 0.1;
  const platformFeeAed = Math.round(partial.grossAed * feeRate);
  const netAed = partial.grossAed - platformFeeAed;
  return {
    ...partial,
    amountAed: netAed,
    grossAed: partial.grossAed,
    platformFeeAed,
    netAed,
  };
}

